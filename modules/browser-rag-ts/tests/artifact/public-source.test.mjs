import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { readPublicSnapshot, resolveBuildSource } from "../../../../scripts/public-source.mjs";

const sha256 = (value) => createHash("sha256").update(value).digest("hex");

async function fixture(t, verification_exclusions = []) {
  const root = await mkdtemp(join(tmpdir(), "rag-public-source-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(join(root, "src"));
  const bytes = Buffer.from("reviewed source\n");
  await writeFile(join(root, "src", "example.txt"), bytes);
  const files = [{ path: "src/example.txt", bytes: bytes.length, sha256: sha256(bytes) }];
  const fingerprint = sha256(JSON.stringify({ schema: "public-source-content/v1", files }) + "\n");
  const manifest = {
    schema: "public-release-manifest/v1", project: "rag-method", status: "pass", manifest_complete: true,
    source_fingerprint_sha256: fingerprint, fingerprint_algorithm: "sha256-json-file-table-v1",
    self_manifest_exclusion: "PUBLIC_MANIFEST.json", verification_exclusions, files,
  };
  const manifestPath = join(root, "PUBLIC_MANIFEST.json");
  await writeFile(manifestPath, JSON.stringify(manifest));
  return { root, bytes, fingerprint, manifest, manifestPath };
}

test("only a complete passing receipt with the exact current source is reviewed", async (t) => {
  const { root, fingerprint } = await fixture(t);
  const expected = { kind: "source-snapshot", fingerprint_sha256: fingerprint };
  assert.deepEqual(readPublicSnapshot(root), expected);
  assert.deepEqual(resolveBuildSource(root), expected);
});

test("editing existing source creates an unreviewed identity without changing the review receipt", async (t) => {
  const { root, fingerprint, manifestPath } = await fixture(t);
  const reviewedBytes = await readFile(manifestPath);
  await writeFile(join(root, "src", "example.txt"), "edited working source\n");
  const current = resolveBuildSource(root);
  assert.equal(current.kind, "working-source");
  assert.equal(current.review_status, "unreviewed");
  assert.notEqual(current.fingerprint_sha256, fingerprint);
  assert.throws(() => readPublicSnapshot(root), /changed after review/);
  assert.deepEqual(await readFile(manifestPath), reviewedBytes);
});

test("new ordinary source files cannot inherit an earlier review", async (t) => {
  const { root, fingerprint, manifestPath } = await fixture(t);
  const reviewedBytes = await readFile(manifestPath);
  await writeFile(join(root, "src", "new-module.mjs"), "export const answer = 42;\n");
  const current = resolveBuildSource(root);
  assert.equal(current.kind, "working-source");
  assert.equal(current.review_status, "unreviewed");
  assert.notEqual(current.fingerprint_sha256, fingerprint);
  assert.throws(() => readPublicSnapshot(root), /complete file inventory differs/);
  assert.deepEqual(await readFile(manifestPath), reviewedBytes);
});

test("only declared generated dependency roots are excluded when a manifest exists", async (t) => {
  const { root, fingerprint } = await fixture(t, ["modules/browser-rag-ts/node_modules"]);
  const dependencies = join(root, "modules", "browser-rag-ts", "node_modules", "prepared");
  await mkdir(dependencies, { recursive: true });
  await writeFile(join(dependencies, "index.js"), "generated dependency\n");
  assert.deepEqual(readPublicSnapshot(root), { kind: "source-snapshot", fingerprint_sha256: fingerprint });
  await writeFile(join(dependencies, "index.js"), "different generated bytes\n");
  assert.equal(resolveBuildSource(root).fingerprint_sha256, fingerprint);
  const undeclared = join(root, "other", "node_modules");
  await mkdir(undeclared, { recursive: true });
  await writeFile(join(undeclared, "index.js"), "ordinary unreviewed file\n");
  assert.equal(resolveBuildSource(root).kind, "working-source");
  assert.notEqual(resolveBuildSource(root).fingerprint_sha256, fingerprint);
});

test("a missing manifest uses project-generated defaults and stays unreviewed", async (t) => {
  const { root, fingerprint, manifestPath } = await fixture(t);
  await rm(manifestPath);
  const dependencies = join(root, "modules", "browser-rag-ts", "node_modules");
  await mkdir(dependencies, { recursive: true });
  await writeFile(join(dependencies, "generated.js"), "prepared dependency\n");
  assert.deepEqual(resolveBuildSource(root), { kind: "working-source", review_status: "unreviewed", fingerprint_sha256: fingerprint });
  await assert.rejects(readFile(manifestPath), { code: "ENOENT" });
  assert.throws(() => readPublicSnapshot(root), { code: "ENOENT" });
});

test("a failed, incomplete, or unspecified review never qualifies matching bytes", async (t) => {
  const { root, fingerprint, manifest, manifestPath } = await fixture(t);
  for (const receipt of [
    { ...manifest, status: "fail" },
    { ...manifest, status: "needs_review" },
    { ...manifest, manifest_complete: false },
    { ...manifest, status: undefined, manifest_complete: undefined },
  ]) {
    await writeFile(manifestPath, JSON.stringify(receipt));
    assert.deepEqual(resolveBuildSource(root), { kind: "working-source", review_status: "unreviewed", fingerprint_sha256: fingerprint });
    assert.throws(() => readPublicSnapshot(root), /review has not passed/);
  }
});

test("manifest fingerprint tampering fails explicitly instead of granting review", async (t) => {
  const { root, manifest, manifestPath } = await fixture(t);
  await writeFile(manifestPath, JSON.stringify({ ...manifest, source_fingerprint_sha256: "0".repeat(64) }));
  assert.throws(() => readPublicSnapshot(root), /fingerprint differs/);
  assert.throws(() => resolveBuildSource(root), /fingerprint differs/);
});

test("a generated exclusion cannot hide ordinary source", async (t) => {
  const { root, manifest, manifestPath } = await fixture(t);
  await writeFile(manifestPath, JSON.stringify({ ...manifest, verification_exclusions: ["src"] }));
  assert.throws(() => resolveBuildSource(root), /exact generated directory roots/);
});

test("Git metadata, credential files, and runtime state do not become build identity inputs", async (t) => {
  const { root, fingerprint } = await fixture(t);
  for (const directory of [".git", ".tools", "runtime-data"]) {
    await mkdir(join(root, directory));
    await writeFile(join(root, directory, "local-state.txt"), "excluded local state\n");
  }
  await writeFile(join(root, ".env"), "EXAMPLE_LOCAL_SETTING=local\n");
  assert.equal(resolveBuildSource(root).fingerprint_sha256, fingerprint);
  await writeFile(join(root, ".env.example"), "EXAMPLE_LOCAL_SETTING=example\n");
  assert.equal(resolveBuildSource(root).kind, "working-source");
  assert.notEqual(resolveBuildSource(root).fingerprint_sha256, fingerprint);
});
