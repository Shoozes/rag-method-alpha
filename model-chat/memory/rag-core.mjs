function fullContractCasefold(value) {
  const normalized = normalizeNfkc(value);
  let output = "";
  for (const scalar of Array.from(normalized)) output += CASEFOLD_V1[scalar] ?? scalar;
  return collapsePythonUnicodeWhitespace(output);
}

