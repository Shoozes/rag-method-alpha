var MICRO_UNITS = 1e6;
function quantizeCosine(value) {
  if (!Number.isFinite(value)) throw new Error("cosine must be finite");
  return Math.max(0, Math.min(MICRO_UNITS, Math.floor(Math.max(0, Math.min(1, value)) * MICRO_UNITS + 0.5)));
}

