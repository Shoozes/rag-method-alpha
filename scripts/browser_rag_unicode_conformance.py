"""Generate and verify browser-rag-ts Unicode conformance assets.

The browser adapter deliberately keeps retrieval lowercase separate from
identity casefolding.  JavaScript does not expose Python's full casefold table,
so this script snapshots the table from the local Python runtime instead of
hand-maintaining a partial compatibility list.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import unicodedata
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
MODULE = ROOT / "modules" / "browser-rag-ts"
TABLE_PATH = MODULE / "src" / "core" / "shared" / "generated" / "casefold-v1.ts"
FIXTURE_PATH = MODULE / "tests" / "fixtures" / "unicode-conformance-v1.json"
PROFILE_PATH = ROOT / "contracts" / "rag-behavior-v2" / "retrieval-profile.json"
GENERATOR_VERSION = "casefold-v1"
def _collapse_contract_whitespace(value: str) -> str:
    return " ".join(value.split())


def _retrieval_lowercase(value: str) -> str:
    return _collapse_contract_whitespace(unicodedata.normalize("NFKC", value).lower())


def _identity_casefold(value: str) -> str:
    return _collapse_contract_whitespace(unicodedata.normalize("NFKC", value).casefold())


def _table() -> dict[str, str]:
    return {
        f"{codepoint:X}": folded
        for codepoint in range(0x110000)
        if not (0xD800 <= codepoint <= 0xDFFF)
        and (folded := chr(codepoint).casefold()) != chr(codepoint)
    }


def _canonical_json(value: Any) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _ts_scalar_string(value: str) -> str:
    return '"' + "".join(f"\\u{{{ord(scalar):X}}}" for scalar in value) + '"'


def _metadata(table: dict[str, str]) -> dict[str, Any]:
    return {
        "generator": "scripts/browser_rag_unicode_conformance.py",
        "generator_version": GENERATOR_VERSION,
        "python_version": sys.version.split()[0],
        "unicode_version": unicodedata.unidata_version,
        "mapping_entries": len(table),
        "table_sha256": hashlib.sha256(_canonical_json(table)).hexdigest(),
    }


def _table_source(table: dict[str, str], metadata: dict[str, Any]) -> str:
    metadata_lines = "\n".join(
        f"  {key}: {json.dumps(value, ensure_ascii=True)}," for key, value in metadata.items()
    )
    rows = "\n".join(
        f"  {_ts_scalar_string(chr(int(codepoint, 16)))}: {_ts_scalar_string(folded)},"
        for codepoint, folded in table.items()
    )
    return (
        "// Generated by scripts/browser_rag_unicode_conformance.py. Do not edit.\n"
        "// Python full casefold table used only for frozen identity normalization.\n"
        "export const CASEFOLD_V1_METADATA = Object.freeze({\n"
        f"{metadata_lines}\n"
        "} as const);\n\n"
        "export const CASEFOLD_V1: Readonly<Record<string, string>> = Object.freeze({\n"
        f"{rows}\n"
        "});\n"
    )


def _fixture(metadata: dict[str, Any]) -> dict[str, Any]:
    values = {
        "street_sharp_s": "Straße",
        "street_ascii": "STRASSE",
        "greek_final_sigma": "ΟΣ",
        "cyrillic": "КИРИЛЛИЦА",
        "cherokee": "Ꭰꭰ",
        "contract_whitespace": "\u0085Alpha\u00A0Beta\u2028Gamma\u2029",
        "combining": "Cafe\u0301",
        "supplementary": "𐀀🧭",
    }
    profile = json.loads(PROFILE_PATH.read_text(encoding="utf-8"))
    return {
        "schema": "browser-rag-ts-unicode-conformance-v1",
        "metadata": metadata,
        "cases": [
            {
                "id": case_id,
                "input": value,
                "retrieval_lowercase": _retrieval_lowercase(value),
                "identity_casefold": _identity_casefold(value),
            }
            for case_id, value in values.items()
        ],
        "distinctions": {
            "street_retrieval_values_must_differ": [
                _retrieval_lowercase(values["street_sharp_s"]),
                _retrieval_lowercase(values["street_ascii"]),
            ],
            "street_identity_values_must_match": _identity_casefold(values["street_sharp_s"]),
        },
        "identity_test_vectors": profile["identity"]["test_vectors"],
        "scope_cases": [
            {"input": "\u00A0workspace:edge\u2028", "normalized": "workspace:edge"},
            {"input": "Persona:Private", "normalized": "Persona:Private"},
        ],
        "invalid_utf16_code_units": ["D800", "DC00"],
    }


def _write_or_check(path: Path, expected: str, check: bool) -> None:
    if check:
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            raise RuntimeError(f"generated Unicode conformance drift: {path.relative_to(ROOT)}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when generated assets differ")
    args = parser.parse_args()
    table = _table()
    metadata = _metadata(table)
    _write_or_check(TABLE_PATH, _table_source(table, metadata), args.check)
    _write_or_check(FIXTURE_PATH, json.dumps(_fixture(metadata), ensure_ascii=False, indent=2) + "\n", args.check)
    print(f"browser-rag Unicode conformance: {'check passed' if args.check else 'generated'} ({metadata['mapping_entries']} mappings, Unicode {metadata['unicode_version']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
