"""Generate the Python-Unicode property boundaries used by browser-rag-ts.

JavaScript normalization follows the browser's current Unicode database, while
the owning Python runtime follows ``unicodedata``. Unicode normalization is
stable for previously assigned characters, so the browser can reproduce the
Python runtime by normalizing assigned runs and treating Python-unassigned
scalars as inert boundaries. Python whitespace and alphanumeric predicates are
also generated because JavaScript may use a newer Unicode property database.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import unicodedata
from pathlib import Path
from collections.abc import Callable
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = (
    ROOT
    / "modules"
    / "browser-rag-ts"
    / "src"
    / "core"
    / "shared"
    / "generated"
    / "python-unicode-v1.ts"
)
GENERATOR_VERSION = "python-unicode-v1"


def _scalar_ranges(predicate: Callable[[int], bool]) -> tuple[list[tuple[int, int]], int]:
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    end: int | None = None
    matching_scalars = 0
    for codepoint in range(sys.maxunicode + 1):
        matches = not (0xD800 <= codepoint <= 0xDFFF) and predicate(codepoint)
        if matches:
            matching_scalars += 1
            if start is None:
                start = end = codepoint
            elif end is not None and codepoint == end + 1:
                end = codepoint
            else:
                if end is None:
                    raise RuntimeError("generated Unicode range is incomplete")
                ranges.append((start, end))
                start = end = codepoint
        elif start is not None:
            if end is None:
                raise RuntimeError("generated Unicode range is incomplete")
            ranges.append((start, end))
            start = end = None
    if start is not None:
        if end is None:
            raise RuntimeError("generated Unicode range is incomplete")
        ranges.append((start, end))
    return ranges, matching_scalars


def _canonical_json(value: Any) -> bytes:
    return json.dumps(value, separators=(",", ":")).encode("utf-8")


def _range_digest(ranges: list[tuple[int, int]]) -> str:
    return hashlib.sha256(
        _canonical_json([[start, end] for start, end in ranges])
    ).hexdigest()


def _range_lines(ranges: list[tuple[int, int]]) -> str:
    return "\n".join(f"  [0x{start:X}, 0x{end:X}]," for start, end in ranges)


def _source(
    assigned_ranges: list[tuple[int, int]],
    assigned_scalars: int,
    alphanumeric_ranges: list[tuple[int, int]],
    alphanumeric_scalars: int,
    whitespace_ranges: list[tuple[int, int]],
    whitespace_scalars: int,
) -> str:
    metadata = {
        "generator": "scripts/browser_rag_nfkc_conformance.py",
        "generator_version": GENERATOR_VERSION,
        "python_version": sys.version.split()[0],
        "unicode_version": unicodedata.unidata_version,
        "assigned_ranges": len(assigned_ranges),
        "assigned_scalars": assigned_scalars,
        "ranges_sha256": _range_digest(assigned_ranges),
        "alphanumeric_ranges": len(alphanumeric_ranges),
        "alphanumeric_scalars": alphanumeric_scalars,
        "alphanumeric_sha256": _range_digest(alphanumeric_ranges),
        "whitespace_ranges": len(whitespace_ranges),
        "whitespace_scalars": whitespace_scalars,
        "whitespace_sha256": _range_digest(whitespace_ranges),
    }
    metadata_lines = "\n".join(
        f"  {key}: {json.dumps(value)}," for key, value in metadata.items()
    )
    return (
        "// Generated by scripts/browser_rag_nfkc_conformance.py. Do not edit.\n"
        "// Python scalar properties pin browser normalization, token, and whitespace behavior.\n"
        "export const PYTHON_UNICODE_V1_METADATA = Object.freeze({\n"
        f"{metadata_lines}\n"
        "} as const);\n\n"
        "export const PYTHON_UNICODE_V1_ASSIGNED_RANGES: "
        "ReadonlyArray<readonly [number, number]> = Object.freeze([\n"
        f"{_range_lines(assigned_ranges)}\n"
        "] as const);\n\n"
        "export const PYTHON_UNICODE_V1_ALPHANUMERIC_RANGES: "
        "ReadonlyArray<readonly [number, number]> = Object.freeze([\n"
        f"{_range_lines(alphanumeric_ranges)}\n"
        "] as const);\n\n"
        "export const PYTHON_UNICODE_V1_WHITESPACE_RANGES: "
        "ReadonlyArray<readonly [number, number]> = Object.freeze([\n"
        f"{_range_lines(whitespace_ranges)}\n"
        "] as const);\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the generated table differs")
    args = parser.parse_args()
    assigned_ranges, assigned_scalars = _scalar_ranges(
        lambda codepoint: unicodedata.category(chr(codepoint)) != "Cn"
    )
    alphanumeric_ranges, alphanumeric_scalars = _scalar_ranges(
        lambda codepoint: chr(codepoint).isalnum()
    )
    whitespace_ranges, whitespace_scalars = _scalar_ranges(
        lambda codepoint: chr(codepoint).isspace()
    )
    expected = _source(
        assigned_ranges,
        assigned_scalars,
        alphanumeric_ranges,
        alphanumeric_scalars,
        whitespace_ranges,
        whitespace_scalars,
    )
    if args.check:
        if not OUTPUT_PATH.is_file() or OUTPUT_PATH.read_text(encoding="utf-8") != expected:
            raise RuntimeError(f"generated Python Unicode boundary drift: {OUTPUT_PATH.relative_to(ROOT)}")
    else:
        OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_PATH.write_text(expected, encoding="utf-8")
    action = "check passed" if args.check else "generated"
    print(
        f"browser-rag Python Unicode boundary: {action} "
        f"({len(assigned_ranges)} assigned ranges, "
        f"{len(alphanumeric_ranges)} alphanumeric ranges, "
        f"{len(whitespace_ranges)} whitespace ranges, Unicode {unicodedata.unidata_version})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
